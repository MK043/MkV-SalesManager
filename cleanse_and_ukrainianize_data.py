def clean_plate(plate):
    if not plate:
        return "AO 7777 MK"
    # Convert RU plate format into UA plate format
    num_match = re.search(r'\d+', plate)
    num = num_match.group(0)[:4].zfill(4) if num_match else "1234"
    regions = ["AO", "BC", "AA", "KA", "AC", "BK", "BX"]
    import random
    reg = regions[hash(plate) % len(regions)]
    suffixes = ["MK", "BT", "CX", "HA", "IE", "KX", "MB"]
    suf = suffixes[(hash(plate) >> 3) % len(suffixes)]
    return f"{reg} {num} {suf}"

def clean_phone(phone):
    if not phone:
        return "+380501234567"
    digits = re.sub(r'\D', '', phone)
    if digits.startswith('7') or digits.startswith('8'):
        digits = '380' + digits[1:]
    elif not digits.startswith('380'):
        digits = '380' + digits[-9:]
    return '+' + digits

def translate_string(s):
    if not isinstance(s, str):
        return s
    # Direct mappings
    if s in name_replacements:
        return name_replacements[s]
    if s in role_replacements:
        return role_replacements[s]
    if s in stage_replacements:
        return stage_replacements[s]
    if s in terms:
        return terms[s]
    
    # Substring replacements
    res = s
    for k, v in name_replacements.items():
        res = res.replace(k, v)
    for k, v in role_replacements.items():
        res = res.replace(k, v)
    for k, v in stage_replacements.items():
        res = res.replace(k, v)
    for k, v in terms.items():
        res = res.replace(k, v)
    
    # Common words
    res = re.sub(r'\bПриёмка\b', 'Прийомка', res)
    res = re.sub(r'\bРемонт\b', 'Ремонт', res)
    res = re.sub(r'\bДиагностика\b', 'Діагностика', res)
    res = re.sub(r'\bМойка\b', 'Мийка', res)
    res = re.sub(r'\bВыдача\b', 'Видача', res)
    res = re.sub(r'\bЗаказ запчастей\b', 'Замовлення запчастин', res)
    res = re.sub(r'\bКонтроль качества\b', 'Контроль якості', res)
    res = re.sub(r'\bСогласование\b', 'Узгодження', res)
    return res

def process_item(val):
    if isinstance(val, dict):
        new_dict = {}
        for k, v in val.items():
            if k == 'plate':
                new_dict[k] = clean_plate(v)
            elif k in ('customer_phone', 'phone'):
                new_dict[k] = clean_phone(v)
            elif k in ('customer_name', 'name', 'full_name'):
                new_dict[k] = translate_string(v)
            else:
                new_dict[k] = process_item(v)
        return new_dict
    elif isinstance(val, list):
        return [process_item(x) for x in val]
    elif isinstance(val, str):
        return translate_string(val)
    else:
        return val

